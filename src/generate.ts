import { mkdir, rm, writeFile, copyFile } from "node:fs/promises";
import path from "node:path";
import { loadCollectionConfig } from "./collection.js";
import { REPOSITORY_ROOT } from "./files.js";
import type { AlertRecipe, CatalogRecord, ValidationIssue } from "./types.js";

function generatedRecipeHeader(recipe: AlertRecipe): string[] {
  return [
    "  # -----------------------------------------------------------------------------",
    `  # Recipe: ${recipe.metadata.alertId}`,
    ...recipe.headerLines.filter((line) => line.startsWith("#")).map((line) => `  ${line}`)
  ];
}

export async function generateMergedAlerts(recipes: AlertRecipe[]): Promise<{ output?: string; issues: ValidationIssue[] }> {
  const collection = await loadCollectionConfig();
  if (!collection.config || collection.issues.length > 0) {
    return { issues: collection.issues };
  }
  const verified = recipes.filter((recipe) => recipe.metadata.status === "verified").sort((left, right) => left.metadata.alertId.localeCompare(right.metadata.alertId));
  const lines = [
    `# 1MB DiscordSRV Alerts collection version ${collection.config.version}, build ${collection.config.build}`,
    "# Generated from verified Alert Recipes. Do not edit this file manually.",
    "# Excludes the 1MoreBlock Live Profile and player-IP reporting.",
    `# Verified with Paper ${collection.config.verifiedRuntime.paper}, Java ${collection.config.verifiedRuntime.java}, DiscordSRV ${collection.config.verifiedRuntime.discordSrv}`,
    "",
    "Alerts:"
  ];

  for (const recipe of verified) {
    lines.push(...generatedRecipeHeader(recipe));
    if (recipe.listBody) {
      lines.push(...recipe.listBody.split("\n"));
    }
  }

  return { output: `${lines.join("\n").replace(/\s+$/, "")}\n`, issues: [] };
}

function recipeTriggers(recipe: AlertRecipe): string[] {
  const triggers = new Set<string>();
  for (const alert of recipe.alerts) {
    const trigger = alert.Trigger;
    if (typeof trigger === "string") {
      triggers.add(trigger);
    } else if (Array.isArray(trigger)) {
      trigger.filter((value): value is string => typeof value === "string").forEach((value) => triggers.add(value));
    }
  }
  return [...triggers].sort();
}

export function catalogRecord(recipe: AlertRecipe): CatalogRecord {
  return {
    id: recipe.metadata.alertId,
    description: recipe.metadata.description,
    plugin: recipe.metadata.plugin,
    version: recipe.metadata.version,
    build: recipe.metadata.build,
    channel: recipe.metadata.channel,
    audience: recipe.metadata.audience,
    triggers: recipeTriggers(recipe),
    authors: recipe.metadata.authors,
    credits: recipe.metadata.credits,
    originUrls: recipe.metadata.originUrls,
    requiredPlugins: recipe.metadata.requiredPlugins,
    verifiedRuntime: {
      discordSrv: recipe.metadata.verifiedDiscordSrv,
      paper: recipe.metadata.verifiedPaper,
      java: recipe.metadata.verifiedJava,
      date: recipe.metadata.verifiedDate
    },
    screenshots: recipe.metadata.screenshots,
    relativePath: recipe.relativePath,
    rawUrl: `https://raw.githubusercontent.com/mrfdev/1MB-DiscordSRV-Alerts/main/${recipe.relativePath}`,
    yaml: recipe.raw
  };
}

export async function writeGeneratedFiles(recipes: AlertRecipe[]): Promise<ValidationIssue[]> {
  const result = await generateMergedAlerts(recipes);
  if (!result.output || result.issues.length > 0) {
    return result.issues;
  }
  const generatedDirectory = path.join(REPOSITORY_ROOT, "dist", "generated");
  await mkdir(generatedDirectory, { recursive: true });
  await writeFile(path.join(generatedDirectory, "alerts.yml"), result.output, "utf8");
  return [];
}

export async function writeSiteData(recipes: AlertRecipe[]): Promise<void> {
  const verified = recipes.filter((recipe) => recipe.metadata.status === "verified").sort((left, right) => left.metadata.alertId.localeCompare(right.metadata.alertId));
  const collection = await loadCollectionConfig();
  if (!collection.config || collection.issues.length > 0) {
    throw new Error("Cannot generate site data from an invalid collection.yml");
  }
  const outputDirectory = path.join(REPOSITORY_ROOT, "site", "public", "generated");
  await rm(outputDirectory, { recursive: true, force: true });
  await mkdir(outputDirectory, { recursive: true });
  await writeFile(path.join(outputDirectory, "catalog.json"), `${JSON.stringify({
    collection: collection.config,
    recipes: verified.map(catalogRecord)
  }, null, 2)}\n`, "utf8");

  for (const recipe of verified) {
    for (const screenshot of recipe.metadata.screenshots) {
      const source = path.join(REPOSITORY_ROOT, screenshot);
      const destination = path.join(outputDirectory, screenshot);
      await mkdir(path.dirname(destination), { recursive: true });
      await copyFile(source, destination);
    }
  }
}
